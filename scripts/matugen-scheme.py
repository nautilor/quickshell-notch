#!/usr/bin/env python3
"""Run matugen for a colour scheme: the accent seeds the tonal colours (primary, containers),
while the scheme's own background, text and outline colours replace matugen's accent-tinted neutrals.

Optionally a third argument (json list of hex colours: the scheme's primary, secondary, tertiary,
error and accents) is classified into the red/orange/yellow/green/cyan/blue/purple custom colours,
so templates that use them (e.g. the nvim palette) get the scheme's real hues instead of fixed ones.

A fourth argument (json object: the scheme's optional "roles" block) is written next to the nvim
palette as roles.lua, so matugen.nvim can reproduce the syntax layout of the scheme's own nvim theme
(role -> "#hex" or {"fg": "#hex", "bold": true, "italic": true}). It is rewritten on every run, empty
when the scheme has no roles, and tagged with the scheme background so the plugin ignores a stale one.

usage: matugen-scheme.py <accent hex> <json {matugen role: hex}> [json [hex, ...]] [json {roles}]
"""
import colorsys
import json
import os
import subprocess
import sys
import tempfile

# canonical hues (degrees) of the custom colour slots
SLOTS = {"red": 355, "orange": 28, "yellow": 50, "green": 100, "cyan": 182, "blue": 215, "purple": 285}
BORROW_RANGE = 75  # an unmatched slot reuses the scheme colour nearest in hue within this range
MATCH_RANGE = 36  # max hue distance for a scheme colour to claim a slot
MIN_SAT = 0.15  # below this a colour is grey and carries no hue


def hsl(hex_):
    r, g, b = (int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    return h * 360, s, l


def to_hex(h, s, l):
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360, l, s)
    return "#%02x%02x%02x" % tuple(round(c * 255) for c in (r, g, b))


def hue_dist(a, b):
    return abs((a - b + 180) % 360 - 180)


def classify(colors, error=None):
    """Map each slot to a hex: scheme colours where one is close in hue (closest pairs first, one
    slot per colour), otherwise the nearest scheme colour, or failing that a colour at the canonical hue with the matched colours' average
    saturation and lightness, so the palette stays coherent (and grey schemes stay grey)."""
    cands = []
    for c in colors:
        c = c.lower()
        if len(c) == 7 and c[0] == "#" and c not in (x[0] for x in cands):
            cands.append((c, *hsl(c)))
    if not cands:
        return {}
    coloured = [c for c in cands if c[2] >= MIN_SAT] or cands
    # closest hue first; very pale colours rank behind vivid ones of similar hue
    # (tokyo night's #b4f9f8 must not beat its #2ac3de for cyan)
    def pairs_for(slots, pool):
        return sorted(
            (hue_dist(c[1], hue) + 250 * max(0, c[3] - 0.78), c[0], slot)
            for c in pool for slot, hue in slots.items()
            if hue_dist(c[1], hue) <= MATCH_RANGE
        )

    pairs = pairs_for(SLOTS, coloured)
    out, used = {}, set()
    # the scheme's error colour is its red, even when another colour is a hair closer
    if error and error.lower() in (c[0] for c in coloured):
        e = next(c for c in coloured if c[0] == error.lower())
        if hue_dist(e[1], SLOTS["red"]) <= MATCH_RANGE:
            used.add(e[0])
            out["red"] = e[0]
    for _, hex_, slot in pairs:
        if hex_ not in used and slot not in out:
            used.add(hex_)
            out[slot] = hex_
    ref = [hsl(h) for h in out.values()] or [c[1:] for c in coloured]
    sat = sum(c[1] for c in ref) / len(ref)
    lig = sum(c[2] for c in ref) / len(ref)
    for slot, hue in SLOTS.items():
        if slot in out:
            continue
        # prefer a colour the scheme really has (gruvbox has no vivid blue or purple, so
        # inventing one would look foreign) and only synthesize when nothing is near
        near = min(coloured, key=lambda c: hue_dist(c[1], hue))
        out[slot] = near[0] if hue_dist(near[1], hue) <= BORROW_RANGE else to_hex(hue, sat, lig)
    return out


accent, overrides = sys.argv[1], json.loads(sys.argv[2])
hues = json.loads(sys.argv[3]) if len(sys.argv) > 3 else []
palette = classify(hues, hues[0] if hues else None)
overrides.update(palette)


def write_roles(roles, background):
    """Write roles.lua for matugen.nvim (path: $MATUGEN_NVIM_ROLES or <state>/nvim/matugen/roles.lua)."""
    state = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
    path = os.environ.get("MATUGEN_NVIM_ROLES") or os.path.join(state, "nvim", "matugen", "roles.lua")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = ["-- generated by matugen-scheme.py", "return {", f'\tbackground = "{background}",', "\troles = {"]
    for name, v in sorted(roles.items()):
        if isinstance(v, str):
            lines.append(f'\t\t["{name}"] = "{v}",')
        elif isinstance(v, dict) and isinstance(v.get("fg"), str):
            flags = "".join(f", {k} = true" for k in ("bold", "italic", "underline") if v.get(k))
            lines.append(f'\t\t["{name}"] = {{ fg = "{v["fg"]}"{flags} }},')
    lines += ["\t},", "}", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


try:
    roles = json.loads(sys.argv[4]) if len(sys.argv) > 4 else {}
    write_roles(roles if isinstance(roles, dict) else {}, overrides.get("background", ""))
except OSError:
    pass  # roles are optional; never block the palette run
dump = subprocess.run(
    ["matugen", "color", "hex", accent, "-m", "dark", "--dry-run", "-j", "hex", "-q"],
    capture_output=True, text=True, check=True,
).stdout
data = json.loads(dump[dump.index("{"):])
for role, hex_ in overrides.items():
    data["colors"][role] = {m: {"color": hex_} for m in ("dark", "default", "light")}
with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
    json.dump(data, f)
try:
    subprocess.run(["matugen", "json", f.name, "-m", "dark"], check=True)
finally:
    os.unlink(f.name)
